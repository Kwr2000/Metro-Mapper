// Generate TypeScript types from the pipeline's exported JSON Schemas
// (run `mm schema` first). Output is committed; CI fails if it drifts.
import { compileFromFile } from "json-schema-to-typescript";
import { writeFileSync } from "node:fs";

const banner = "/* Generated by scripts/gen-types.mjs from schemas/*.schema.json. Do not edit. */";
for (const name of ["registry", "health"]) {
  const ts = await compileFromFile(`../schemas/${name}.schema.json`, {
    bannerComment: banner,
    additionalProperties: false,
    style: { singleQuote: false },
  });
  writeFileSync(`src/generated/${name}.ts`, ts);
  console.log(`wrote src/generated/${name}.ts`);
}
