"""Generate the nine registry-driven access manifests, sharing one data bundle."""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[2]
PALETTE = ["#edf8e9", "#bae4b3", "#74c476", "#31a354", "#006d2c"]
DESCRIPTION = "Typical minutes from homes in this area (2020 census blocks, weighted by population) along OpenStreetMap streets and paths. Flat speeds; no traffic, hills or crossings. OSM coverage of shops and paths varies."
TAGS = {"grocery": "Grocery: shop=supermarket|grocery|greengrocer.", "park": "Parks: leisure=park, at least 0.1 ha; boundary nodes are treated as entrances.",
    "school": "School: amenity=school. Context only; not a school or attendance-zone assignment.",
    "basket": "Daily needs: pharmacy (amenity=pharmacy or shop=chemist), food (amenity=cafe|restaurant|fast_food), hardware (shop=hardware|doityourself), bank (amenity=bank), library (amenity=library). Basket is the longest of the five nearest times."}
MEASURES = [(f"{mode}_{dest}", f"{mode.title()} to {label} (minutes)") for mode in ("walk", "bike") for dest, label in
            (("grocery", "grocery"), ("park", "park"), ("school", "school"), ("basket", "daily needs"))]


def manifest(identity, field, title, breaks, colors, order):
    popup = [{"field": name, "label": label, "format": "number", "annotation_field": name + "_note"} for name, label in MEASURES]
    popup += [{"field": "transit_per_hour", "label": "CapMetro departures per hour (7–9 am)", "format": "number", "annotation_field": "transit_note"},
              {"field": "transit_departures_7_9", "label": "CapMetro departures 7–9 am (2 hours)", "format": "number"}]
    popup = [next(row for row in popup if row["field"] == field), *[row for row in popup if row["field"] != field]]
    popup += [{"field": name, "label": label} for name, label in (("access_note", "Access note"), ("transit_note", "Transit coverage"),
        ("osm_as_of", "OpenStreetMap as of"), ("gtfs_feed_version", "GTFS feed version"), ("service_date", "Transit service date"), ("geoid", "GEOID"))]
    steps = ["step", ["get", field], colors[0]]
    for threshold, color in zip(breaks, colors[1:]):
        steps.extend((threshold, color))
    labels = [f"Below {breaks[0]}", *[f"{a} to below {b}" for a, b in zip(breaks, breaks[1:])], f"{breaks[-1]} or more"]
    return {"compare": {"field": field, "method": "ratio", "breaks": [.67, .9, 1.1, 1.5],
            "direction": "higher_is_better" if field == "transit_per_hour" else "lower_is_better"}, "id": identity, "title": title, "group": "Access", "description": DESCRIPTION, "source": "access", "geometry": "polygon", "join": "block_group",
        "dataset": "block_group", "data_bundle": "access_block_group", "publish": "geojson", "default_visible": False,
        "style": {"type": "fill", "paint": {"fill-opacity": .55, "fill-color": ["case", ["==", ["get", field], None], "#bdbdbd", steps]}},
        "popup": popup, "legend": [{"label": label, "color": color} for label, color in zip(labels, colors)] + [{"label": "Not available", "color": "#bdbdbd"}],
        "coverage": "study_area", "refresh": "monthly", "attribution": "© OpenStreetMap contributors; Capital Metro (CMTA) GTFS; U.S. Census Bureau",
        "license": "ODbL 1.0 (derived from OpenStreetMap); CMTA Open Data License", "order": order}


def main():
    for i, dest in enumerate(TAGS):
        for mode, label in (("walk", "Walk"), ("bike", "Bike")):
            doc = manifest(f"access_{dest}_{mode}", f"{mode}_{dest}", f"{label} to {dest if dest != 'basket' else 'daily needs'} (minutes)",
                [5, 10, 20, 30] if mode == "walk" else [3, 5, 10, 15], PALETTE[::-1], 80 + 2 * i + (mode == "bike"))
            doc["variant"] = {"family": "access_" + dest, "key": mode, "label": label}
            doc["description"] += " " + TAGS[dest]
            (ROOT / "layers" / (doc["id"] + ".yaml")).write_text("# Generated by adapters/access/make_layers.py\n" + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True))
    doc = manifest("access_transit", "transit_per_hour", "CapMetro departures per hour (7–9 am)", [1, 4, 8, 16], PALETTE, 88)
    doc["description"] += " Scheduled departures on a representative Wednesday at stops within 800 m along the walk network; each trip counts once. CapMetro only; other agencies are not included yet."
    (ROOT / "layers/access_transit.yaml").write_text("# Generated by adapters/access/make_layers.py\n" + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True))


if __name__ == "__main__":
    main()
