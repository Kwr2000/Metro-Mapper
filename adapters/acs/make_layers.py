"""Regenerate committed ACS manifests: python adapters/acs/make_layers.py."""

import argparse
from pathlib import Path

import yaml
from metrics import ATTRIBUTION, BLUE, METRICS, MISSING, SCALES, VINTAGE


def display(value, fmt):
    if fmt == "percent":
        return f"{value * 100:g}%"
    return ("$" if fmt == "currency" else "") + f"{value:,}"


def manifests():
    for index, (metric, (title, fmt, _, _, breaks)) in enumerate(METRICS.items()):
        labels = [f"Below {display(breaks[0], fmt)} estimate"]
        labels += [f"{display(left, fmt)} to below {display(right, fmt)} estimate"
                   for left, right in zip(breaks, breaks[1:])]
        labels += [f"{display(breaks[-1], fmt)} or more estimate"]
        for scale, label in SCALES.items():
            suffix = "bg" if scale == "block_group" else "tract"
            layer_id = f"acs_{metric}_{suffix}"
            step = ["step", ["get", metric], BLUE[0]]
            for threshold, color in zip(breaks, BLUE[1:]):
                step += [threshold, color]
            compare = {}
            if metric != "population":
                compare = {"compare": {"field": metric, "benchmark_field": metric,
                    "method": "ratio" if fmt == "currency" else "difference",
                    "breaks": [0.67, 0.9, 1.1, 1.5] if fmt == "currency" else
                        ([-5, -2, 2, 5] if metric == "median_age" else
                         [-15, -5, 5, 15] if metric == "median_year_built" else [-.10, -.03, .03, .10]),
                    "direction": "neutral", "unit": "" if fmt == "currency" else
                        ("pp" if fmt == "percent" else "years")}}
            yield layer_id, {**compare,
                "id": layer_id, "title": title + " estimate", "group": "People",
                "description": VINTAGE + ". Whole-area estimates on 2020 Census boundaries. "
                    "Block groups are finer but noisier; tracts are steadier. Context and filters only.",
                "source": "acs", "geometry": "polygon", "join": scale, "dataset": scale,
                "publish": "geojson", "variant": {"family": metric, "key": scale, "label": label},
                "data_bundle": "acs_" + scale, "demographic": True, "default_visible": False,
                "style": {"type": "fill", "paint": {"fill-opacity": .55,
                    "fill-color": ["case", ["==", ["get", metric], None], MISSING, step]}},
                "popup": [{"field": metric, "label": title + " estimate", "format": fmt,
                    "moe_field": metric + "_moe", "reliability_field": metric + "_reliability",
                    "annotation_field": metric + "_annotation", "display_field": metric + "_display"},
                    {"field": "geoid", "label": "GEOID"}, {"field": "geography", "label": "Geography"},
                    {"field": "vintage", "label": "Vintage"}],
                "legend": [{"label": text, "color": color} for text, color in zip(labels, BLUE)]
                    + [{"label": "Estimate unavailable", "color": MISSING}],
                "coverage": "study_area", "refresh": "annual", "attribution": ATTRIBUTION,
                "license": "Public domain", "order": 100 + index * 2 + (scale == "tract"),
            }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "layers")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    for layer_id, doc in manifests():
        (args.output / f"{layer_id}.yaml").write_text(
            "# Generated by adapters/acs/make_layers.py; edit the generator.\n"
            + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True))


if __name__ == "__main__":
    main()
