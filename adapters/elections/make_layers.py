"""Generate two manifest-only context layers with a common precinct data bundle."""
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[2]
DESCRIPTION = ("Official general-election results by voting precinct, from the Texas Legislative Council. "
               "Texas has no party registration; registered voters include everyone registered. "
               "Precincts with fewer than 50 votes are not shown. For context only: never used in any score or ranking.")


def manifests():
    popup = [{"field": "precinct", "label": "Precinct"}, {"field": "county", "label": "County"}]
    for y in (2024, 2020):
        for k, label, fmt in (("dem_name", "Democratic candidate", "text"), ("dem", "Democratic votes", "number"),
                ("dem_share", "Democratic share", "percent"), ("rep_name", "Republican candidate", "text"),
                ("rep", "Republican votes", "number"), ("rep_share", "Republican share", "percent"),
                ("other", "Other presidential votes", "number"), ("total", "Total presidential votes", "number"),
                ("margin", "Lead", "percent")):
            field = {"field": f"pres_{y}_{k}", "label": f"{y} {label}", "format": fmt}
            if k == "margin":
                field["display_field"] = f"pres_{y}_lead"  # e.g. "Harris +61.8 pts"
            popup.append(field)
    for y in (2024, 2020):
        for k, label, fmt in (("registered", "Registered voters (all parties)", "number"),
                              ("ballots", "Ballots cast", "number"), ("turnout", "Turnout", "percent")):
            popup.append({"field": f"{k}_{y}", "label": f"{y} {label}", "format": fmt})
    popup += [{"field": "election_note", "label": "Note", "hide_if_empty": True},
              {"field": "source_note", "label": "Source note"}]
    common = dict(group="People", description=DESCRIPTION, source="elections", geometry="polygon", join="precinct",
                  dataset="precinct", publish="geojson", data_bundle="elections_precinct", demographic=True,
                  default_visible=False, popup=popup, popup_title="Presidential votes and turnout by precinct", coverage="study_area", refresh="annual",
                  attribution="Texas Legislative Council, Capitol Data Portal", license="CC BY (Texas Legislative Council)")
    palettes = [
        ("president", "2024 presidential vote by precinct", "pres_2024_margin",
         ["#2166ac", "#67a9cf", "#d1e5f0", "#f7f7f7", "#fddbc7", "#ef8a62", "#b2182b"],
         [-.4, -.2, -.05, .05, .2, .4],
         ["Democratic lead 40+ pts", "Democratic lead 20–40", "Democratic lead 5–20", "Within 5 pts",
          "Republican lead 5–20", "Republican lead 20–40", "Republican lead 40+ pts"]),
        ("turnout", "2024 turnout by precinct (ballots ÷ registered voters)", "turnout_2024",
         ["#eff3ff", "#bdd7e7", "#6baed6", "#3182bd", "#08519c"], [.5, .6, .7, .8],
         ["Below 50%", "50% to below 60%", "60% to below 70%", "70% to below 80%", "80% or more"]),
    ]
    for i, (name, title, field, colors, breaks, labels) in enumerate(palettes):
        step = ["step", ["get", field], colors[0]]
        for threshold, color in zip(breaks, colors[1:]):
            step.extend([threshold, color])
        yield {"id": f"elections_{name}_2024", "title": title, **common,
               "style": {"type": "fill", "paint": {"fill-opacity": .55,
                         "fill-color": ["case", ["==", ["get", field], None], "#bdbdbd", step]}},
               "legend": [{"label": label, "color": color} for label, color in zip(labels, colors)] +
                         [{"label": "Not shown", "color": "#bdbdbd"}], "order": 150 + i}


if __name__ == "__main__":
    for manifest in manifests():
        (ROOT / "layers" / (manifest["id"] + ".yaml")).write_text(
            "# Generated by adapters/elections/make_layers.py; edit the generator.\n" +
            yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True))
